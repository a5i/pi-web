/**
 * Regenerates styles/elements-scoped.css from the installed
 * @stoplight/elements stylesheet.
 *
 * Re-run after bumping @stoplight/elements:
 *
 *   node scripts/scope-elements-styles.mjs
 *
 * @stoplight/elements/styles.min.css carries a Tailwind preflight (html, body,
 * *, p, h1-h6, code, table, ...) and :root variable definitions that would
 * restyle the whole app — including pi-web's own --font-mono — the moment the
 * preview chunk loads it. Instead of importing the original, the chunk imports
 * this generated copy in which every selector is scoped under
 * .openapi-preview-scope:
 *
 *   :root, html, body  ->  .openapi-preview-scope
 *   [data-theme=X] ... ->  .openapi-preview-scope[data-theme=X] ...
 *   anything else      ->  .openapi-preview-scope <selector>
 *
 * Because the variables land on the wrapper, mosaic's [data-theme=dark] rules
 * work when the wrapper carries data-theme="dark" (OpenApiPreviewChunk sets it
 * from useTheme()).
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(root, "node_modules", "@stoplight", "elements", "styles.min.css");
const TARGET = path.join(root, "styles", "elements-scoped.css");
const SCOPE = ".openapi-preview-scope";

const { version } = JSON.parse(
  await readFile(path.join(root, "node_modules", "@stoplight", "elements", "package.json"), "utf8"),
);

function scopeCompoundSelector(compound) {
  if (compound.startsWith(":root")) return SCOPE + compound.slice(":root".length);
  // Preflight resets on html/body apply to the wrapper itself; the pane is the
  // subtree these rules were meant to seed.
  const htmlBody = /^(html|body)(?![\w-])(.*)$/.exec(compound);
  if (htmlBody) return SCOPE + htmlBody[2];
  // Mosaic's theme selectors must keep matching the attribute, but on the
  // wrapper — html[data-theme] never appears inside the pane.
  const theme = /^\[data-theme=([^\]]+)\](.*)$/.exec(compound);
  if (theme) return `${SCOPE}[data-theme=${theme[1]}]${theme[2]}`;
  if (compound.includes("[data-theme=")) {
    throw new Error(`Unsupported nested [data-theme] selector: ${compound}`);
  }
  return `${SCOPE} ${compound}`;
}

function scopeSelector(selector) {
  return selector
    .split(",")
    .map((compound) => compound.trim())
    .filter(Boolean)
    .map(scopeCompoundSelector)
    .join(",\n");
}

const ast = postcss.parse(await readFile(SOURCE, "utf8"), { from: SOURCE });

ast.walkRules((rule) => {
  const parent = rule.parent;
  // Keyframe steps (from/to/0%) are not selectors; @font-face has none.
  if (parent && parent.type === "atrule" && ["keyframes", "-webkit-keyframes", "font-face"].includes(parent.name)) return;
  rule.selector = scopeSelector(rule.selector);
});

const header = `/*
 * Generated by scripts/scope-elements-styles.mjs from
 * @stoplight/elements@${version} styles.min.css — do not edit by hand;
 * re-run the script after bumping the package.
 *
 * Every selector is scoped under ${SCOPE} so Elements' Tailwind preflight
 * and :root variables cannot leak into the rest of the app. [data-theme]
 * selectors are bound to the wrapper element, which OpenApiPreviewChunk
 * sets to "light" or "dark" from useTheme().
 */

`;

const output = header + ast.toResult().css;
await writeFile(TARGET, output);

// Nothing scoped may survive: any of these in the output would leak globally.
const result = await readFile(TARGET, "utf8");
for (const leaked of [/(^|[^.\w-):])root(?![\w-])/, /(^|[^.\w-)>+~ ])(html|body)(?![\w-])/]) {
  const match = leaked.exec(result.replace(header, ""));
  if (match) throw new Error(`Unscoped selector fragment survived: ${match[0]}`);
}

console.log(`styles/elements-scoped.css written from @stoplight/elements@${version} (${result.length} bytes)`);
